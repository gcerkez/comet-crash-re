#!/usr/bin/env python3
"""patch_job188300_scan.py -- native loop for SPU job 0x188300's target scan.

Job 0x188300 (combat / entity simulation) spends most of its time in one inner
loop: blocks 0x6B88 (unpack the next candidate, test the cursor) and 0x6AA0
(the candidate: distance from the current point -- squared length, frsqest +
fi + one Newton step -- and keep the nearest that passes a bitmask). In the
lift every candidate is two block hops, each operation reading and writing
ctx->gpr in memory. In a heavy fight this one loop was ~13% of the process.

This script GENERATES the native loop from the lift itself -- the same helper
calls, in the same order, on local variables instead of ctx->gpr -- so the
result is exact by construction and nothing game-derived is stored in this
repository: the generated file lives in the workspace next to the lift.

  1. job188300_scan.c (workspace, generated): int cc_job188300_scan(ctx),
     which runs  loop { 0x6B88 body; if exit: break; 0x6AA0 body }  then the
     pass tail, writes every register back, and returns 1 to continue at
     0x69A0 or 2 for 0x6BF8 (0 = disabled: run the lift).
  2. spu/spu_job_00188300/spu_recomp.c: the top of func_00006B88 calls it.
  3. CMakeLists.txt: the generated TU is added.

Run-time switches: CC_JOB188300_SCAN=0 (or PS3_NO_JOB_OVERRIDE=1) runs the
lift unchanged. CC_JOB188300_VERIFY=1 runs the native loop on a copy of the
registers while the lift runs for real, and at the loop's exit (0x69A0 or
0x6BF8, hooked too) compares all 128 registers and the exit taken.

Usage: patch_job188300_scan.py [workspace-dir]   (default ~/tools/cc-recomp)
"""
import re
import sys
from pathlib import Path

MARKER = "JOB188300 SCAN OVERRIDE"
JOB = "spu_job_00188300"


def body_of(src: str, fn: str) -> list[str]:
    m = re.search(r"^void %s\(spu_context\* ctx\) \{\n(.*?)^\}\n" % re.escape(fn), src, re.S | re.M)
    assert m, f"function {fn} not found"
    return [l.strip() for l in m.group(1).splitlines() if l.strip()]


def is_noise(l: str) -> bool:
    return l in ("/* nop */;", "/* branch hint (ignored) */;")


def localize(l: str) -> str:
    return re.sub(r"ctx->gpr\[(\d+)\]", r"r\1", l)


def regs(lines: list[str]) -> tuple[set, set]:
    used, written = set(), set()
    for l in lines:
        for n in re.findall(r"ctx->gpr\[(\d+)\]", l):
            used.add(int(n))
        m = re.match(r"ctx->gpr\[(\d+)\] = ", l)
        if m:
            written.add(int(m.group(1)))
    return used, written


def main() -> int:
    ws = Path(sys.argv[1] if len(sys.argv) > 1 else "~/tools/cc-recomp").expanduser()
    job_c = ws / "spu" / JOB / "spu_recomp.c"
    cmake = ws / "CMakeLists.txt"
    out_c = ws / "job188300_scan.c"
    src = job_c.read_text()

    # The lift as generated (the patch inserts its call at the top of 6B88;
    # strip it when re-running so the generator sees the original body).
    fn_ctl, fn_body = f"{JOB}_spu_func_00006B88", f"{JOB}_spu_func_00006AA0"
    # (the hook is three lines, all mentioning _scan)
    ctl = [l for l in body_of(src, fn_ctl) if MARKER not in l and "_scan" not in l]
    body = body_of(src, fn_body)

    # 6AA0: straight-line statements, then the hop back to 6B88.
    assert body[-1] == "{ SPU_DIRECT(ctx, 0x6B88, %s); }" % fn_ctl, body[-1]
    body_stmts = [l for l in body[:-1] if not is_noise(l)]
    # 6B88: statements, the loop test, the pass tail, the two exits.
    t_loop = "if (ctx->gpr[69]._u32[0] == 0) { SPU_DIRECT(ctx, 0x6AA0, %s); }" % fn_body
    t_69a0 = "if (ctx->gpr[14]._u32[0] == 0) { SPU_DIRECT(ctx, 0x69A0, %s_spu_func_000069A0); }" % JOB
    t_6bf8 = "{ SPU_DIRECT(ctx, 0x6BF8, %s_spu_func_00006BF8); }" % JOB
    i_loop, i_69a0 = ctl.index(t_loop), ctl.index(t_69a0)
    assert ctl[-1] == t_6bf8 and i_69a0 == len(ctl) - 2 and i_loop < i_69a0, "6B88 shape changed"
    ctl_stmts = [l for l in ctl[:i_loop] if not is_noise(l)]
    tail_stmts = [l for l in ctl[i_loop + 1:i_69a0] if not is_noise(l)]
    for l in body_stmts + ctl_stmts + tail_stmts:
        assert l.startswith("ctx->gpr[") and l.endswith(";") and "SPU_DIRECT" not in l and "if " not in l, \
            f"unexpected statement in the scan loop: {l}"

    used, written = regs(body_stmts + ctl_stmts + tail_stmts + [t_loop, t_69a0])
    rs = sorted(used)
    ind = "        "
    gen = []
    gen.append("/* GENERATED by comet-crash-re/recomp/scripts/patch_job188300_scan.py from")
    gen.append(f" * {JOB}/spu_recomp.c (func_00006B88 + func_00006AA0). Do not edit: re-run")
    gen.append(" * the script after a re-lift. Exact by construction: the lift's helper")
    gen.append(" * calls in the lift's order, on locals instead of ctx->gpr. */")
    gen.append('#include <stdio.h>')
    gen.append('#include <stdlib.h>')
    gen.append('#include <string.h>')
    gen.append('#include "spu_context.h"')
    gen.append('#include "spu_helpers.h"')
    gen.append("")
    gen.append("static int scan_enabled(void)")
    gen.append("{")
    gen.append("    static int on = -1;")
    gen.append("    if (on < 0) {")
    gen.append('        const char *a = getenv("CC_JOB188300_SCAN"), *b = getenv("PS3_NO_JOB_OVERRIDE");')
    gen.append("        on = !((a && *a && atoi(a) == 0) || (b && *b && atoi(b) != 0));")
    gen.append("    }")
    gen.append("    return on;")
    gen.append("}")
    gen.append("")
    gen.append("/* 1: continue at 0x69A0; 2: continue at 0x6BF8. Reads LS, writes only G. */")
    gen.append("static int scan_core(spu_context* ctx, u128* G)")
    gen.append("{")
    for n in rs:
        gen.append(f"    u128 r{n} = G[{n}];")
    gen.append("    for (;;) {")
    gen.append(f"{ind}/* 0x6B88 */")
    gen += [ind + localize(l) for l in ctl_stmts]
    gen.append(f"{ind}if (r69._u32[0] != 0) break;")
    gen.append(f"{ind}/* 0x6AA0 */")
    gen += [ind + localize(l) for l in body_stmts]
    gen.append("    }")
    gen.append("    /* pass tail */")
    gen += ["    " + localize(l) for l in tail_stmts]
    for n in sorted(written):
        gen.append(f"    G[{n}] = r{n};")
    gen.append("    return r14._u32[0] == 0 ? 1 : 2;")
    gen.append("}")
    gen.append("")
    gen.append("/* Verify mode: the native result on a register copy, checked at the lift's exit. */")
    gen.append("static int verify_on = -1;")
    gen.append("static _Thread_local struct { int pending, ret; u128 G[128]; } vs;")
    gen.append("static unsigned long long v_checked, v_bad;")
    gen.append("")
    gen.append("/* 0: run the lift (disabled, or verifying); 1: go to 0x69A0; 2: go to 0x6BF8. */")
    gen.append("int cc_job188300_scan(spu_context* ctx)")
    gen.append("{")
    gen.append("    if (!scan_enabled()) return 0;")
    gen.append("    if (verify_on < 0) { const char *v = getenv(\"CC_JOB188300_VERIFY\"); verify_on = v && atoi(v) == 1; }")
    gen.append("    if (verify_on) {")
    gen.append("        memcpy(vs.G, ctx->gpr, sizeof vs.G);")
    gen.append("        vs.ret = scan_core(ctx, vs.G);")
    gen.append("        vs.pending = 1;")
    gen.append("        return 0;")
    gen.append("    }")
    gen.append("    return scan_core(ctx, ctx->gpr);")
    gen.append("}")
    gen.append("")
    gen.append("/* At the top of 0x69A0 (where=1) and 0x6BF8 (where=2): compare a pending check. */")
    gen.append("void cc_job188300_scan_check(spu_context* ctx, int where)")
    gen.append("{")
    gen.append("    if (!vs.pending) return;")
    gen.append("    vs.pending = 0;")
    gen.append("    const int same = where == vs.ret && memcmp(vs.G, ctx->gpr, sizeof vs.G) == 0;")
    gen.append("    const unsigned long long n = __atomic_add_fetch(&v_checked, 1, __ATOMIC_RELAXED);")
    gen.append("    if (!same) {")
    gen.append("        const unsigned long long b = __atomic_add_fetch(&v_bad, 1, __ATOMIC_RELAXED);")
    gen.append("        if (b <= 5) {")
    gen.append("            int r = 0; while (r < 128 && memcmp(&vs.G[r], &ctx->gpr[r], 16) == 0) r++;")
    gen.append("            fprintf(stderr, \"[JOB188300 VERIFY] MISMATCH #%llu: exit lift=%d native=%d first reg r%d\\n\", b, where, vs.ret, r);")
    gen.append("        }")
    gen.append("    }")
    gen.append("    if (n % 200000 == 0)")
    gen.append("        fprintf(stderr, \"[JOB188300 VERIFY] %llu scans compared, %llu mismatches\\n\", n, v_bad);")
    gen.append("}")
    new_c = "\n".join(gen) + "\n"

    # call site: the top of func_00006B88
    head = f"void {fn_ctl}(spu_context* ctx) {{\n"
    assert src.count(head) == 1
    hook = (f"        {{ const int _scan = cc_job188300_scan(ctx); /* {MARKER} */\n"
            f"          if (_scan == 1) {{ SPU_DIRECT(ctx, 0x69A0, {JOB}_spu_func_000069A0); }}\n"
            f"          if (_scan == 2) {{ SPU_DIRECT(ctx, 0x6BF8, {JOB}_spu_func_00006BF8); }} }}\n")
    chk = []
    for addr, where in (("000069A0", 1), ("00006BF8", 2)):
        h = f"void {JOB}_spu_func_{addr}(spu_context* ctx) {{\n"
        assert src.count(h) == 1, f"no {addr}"
        chk.append((h, h + f"        cc_job188300_scan_check(ctx, {where}); /* {MARKER} */\n"))
    new_src = src
    if MARKER not in src:
        inc = '#include "spu_recomp.h"'
        assert src.count(inc) == 1
        new_src = new_src.replace(inc, inc + f"\nextern int cc_job188300_scan(spu_context* ctx); /* {MARKER} */"
                                  f"\nextern void cc_job188300_scan_check(spu_context* ctx, int where); /* {MARKER} */", 1)
        new_src = new_src.replace(head, head + hook, 1)
        for h, hh in chk:
            new_src = new_src.replace(h, hh, 1)
        print(f"{job_c}: call site added at the top of func_00006B88")
    else:
        print(f"{job_c}: already patched")

    cm = cmake.read_text()
    new_cm = cm
    if "job188300_scan.c" not in cm:
        anchor = "    main.cpp\n    stubs.cpp\n"
        assert cm.count(anchor) == 1, "cmake anchor"
        new_cm = cm.replace(anchor, anchor + "    job188300_scan.c\n", 1)
        print(f"{cmake}: generated TU added")

    if not out_c.exists() or out_c.read_text() != new_c:
        out_c.write_text(new_c)
        print(f"{out_c}: generated ({len(rs)} registers, {len(body_stmts) + len(ctl_stmts)} ops per candidate)")
    if new_src != src:
        job_c.write_text(new_src)
    if new_cm != cm:
        cmake.write_text(new_cm)
    print("done")
    return 0


if __name__ == "__main__":
    sys.exit(main())
