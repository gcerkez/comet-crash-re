#!/usr/bin/env python3
"""Generate native/src/language1.inc from the extracted English table.

The game's local_text.cpp loads strings by index from language1.utf;
the native host mirrors that: a plain array indexed exactly like the
original. This script converts analysis/language/language1.txt into a
C array. Non-ASCII glyphs the host's debug font can't draw are folded
((R), (TM), ae, ...); the two-character sequence \\n in the source text
is the game's own newline marker and is emitted as a C newline escape.

Usage: gen_text_table.py <language1.txt> <out language1.inc>
"""

import sys

FOLD = {
    "®": "(R)",
    "™": "(TM)",
    "æ": "ae",
    "Æ": "Ae",
    "©": "(C)",
    "…": "...",
    "–": "-",
    "—": "-",
    "‘": "'",
    "’": "'",
    "“": '"',
    "”": '"',
}


def c_escape(text: str) -> str:
    out = []
    i = 0
    while i < len(text):
        ch = text[i]
        if ch == "\\" and i + 1 < len(text) and text[i + 1] == "n":
            out.append("\\n")  # game's newline marker -> C escape
            i += 2
            continue
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\t":
            out.append("\\t")
        elif ch in FOLD:
            out.append(FOLD[ch])
        elif ord(ch) < 128:
            out.append(ch)
        else:
            out.append("?")  # anything else the debug font cannot show
        i += 1
    return "".join(out)


def main() -> int:
    src_path, out_path = sys.argv[1], sys.argv[2]
    entries: dict[int, str] = {}
    for line in open(src_path, encoding="utf-8").read().splitlines():
        if "\t" not in line:
            continue
        idx, text = line.split("\t", 1)
        # The credits entry embeds real tabs; the extractor kept them,
        # so any further tab-separated fields belong to the text.
        entries[int(idx)] = text
    count = max(entries) + 1
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("// GENERATED by scripts/gen_text_table.py from\n")
        f.write("// analysis/language/language1.txt — do not edit by hand.\n")
        f.write("// Index-compatible with the game's language1 string table.\n\n")
        f.write("static const char* const kLanguage1[] = {\n")
        for i in range(count):
            f.write(f'    "{c_escape(entries.get(i, ""))}",  // {i}\n')
        f.write("};\n")
        f.write(f"static const int kLanguage1Count = {count};\n")
    print(f"wrote {count} strings to {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
